(() => {
  const hero = document.querySelector('.hero--alora');
  if (!hero || matchMedia('(prefers-reduced-motion: reduce)').matches || matchMedia('(max-width: 679px)').matches) return;
  const media = hero.querySelector('.hero__media');
  const canvas = document.createElement('canvas');
  canvas.className = 'alora-gloss-canvas';
  canvas.setAttribute('aria-hidden', 'true');
  media.append(canvas);
  const gl = canvas.getContext('webgl', { alpha: true, antialias: false, powerPreference: 'low-power' });
  if (!gl) return;
  const vertex = 'attribute vec2 p; void main(){gl_Position=vec4(p,0.,1.);}';
  const fragment = `precision mediump float; uniform float t; uniform vec2 r; uniform vec2 m;
    void main(){vec2 uv=gl_FragCoord.xy/r; vec2 p=uv-.5; p.x*=r.x/r.y;
    float a=sin(p.x*3.4+t*.12+sin(p.y*4.0+t*.08))*0.5+0.5;
    float b=sin(p.y*5.0-t*.10+sin(p.x*3.0))*0.5+0.5;
    float ribbon=smoothstep(.42,.78,a*b+sin(p.x*2.0+p.y*3.0+t*.08)*.12);
    float cursor=exp(-length(p-vec2((m.x-.5)*r.x/r.y,m.y-.5))*3.2);
    vec3 alab=vec3(.98,.97,.95), pearl=vec3(.937,.902,.847), honey=vec3(.875,.769,.608), bronze=vec3(.722,.608,.471);
    vec3 c=mix(alab,pearl,ribbon*.52); c=mix(c,honey,smoothstep(.5,1.,a)*.34); c=mix(c,bronze,cursor*.13);
    float alpha=(.08+ribbon*.12+cursor*.06); gl_FragColor=vec4(c,alpha);}`;
  const compile=(type,src)=>{const s=gl.createShader(type);gl.shaderSource(s,src);gl.compileShader(s);return s;};
  const program=gl.createProgram();gl.attachShader(program,compile(gl.VERTEX_SHADER,vertex));gl.attachShader(program,compile(gl.FRAGMENT_SHADER,fragment));gl.linkProgram(program);gl.useProgram(program);
  const buf=gl.createBuffer();gl.bindBuffer(gl.ARRAY_BUFFER,buf);gl.bufferData(gl.ARRAY_BUFFER,new Float32Array([-1,-1,1,-1,-1,1,1,1]),gl.STATIC_DRAW);
  const loc=gl.getAttribLocation(program,'p');gl.enableVertexAttribArray(loc);gl.vertexAttribPointer(loc,2,gl.FLOAT,false,0,0);
  const time=gl.getUniformLocation(program,'t'), res=gl.getUniformLocation(program,'r'), mouse=gl.getUniformLocation(program,'m');
  let px=.5,py=.5,tx=.5,ty=.5,raf=0,visible=true;
  const resize=()=>{const d=Math.min(devicePixelRatio,1.5),w=canvas.clientWidth,h=canvas.clientHeight;canvas.width=w*d;canvas.height=h*d;gl.viewport(0,0,canvas.width,canvas.height);gl.uniform2f(res,canvas.width,canvas.height);};
  const render=(now)=>{if(!visible)return;px+=(tx-px)*.035;py+=(ty-py)*.035;gl.uniform1f(time,now*.001);gl.uniform2f(mouse,px,py);gl.drawArrays(gl.TRIANGLE_STRIP,0,4);raf=requestAnimationFrame(render);};
  hero.addEventListener('pointermove',e=>{const b=hero.getBoundingClientRect();tx=(e.clientX-b.left)/b.width;ty=1-(e.clientY-b.top)/b.height;},{passive:true});
  new ResizeObserver(resize).observe(media); resize();
  new IntersectionObserver(([entry])=>{visible=entry.isIntersecting;if(visible&&!raf)raf=requestAnimationFrame(render);if(!visible){cancelAnimationFrame(raf);raf=0;}},{threshold:0.01}).observe(hero);
  canvas.classList.add('is-live');raf=requestAnimationFrame(render);
})();
